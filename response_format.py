"""Keep explicit no-answer responses free of misleading source links."""

import re


def is_no_answer(text):
    return bool(re.search(
        r"\b(?:i|we)\s+(?:could not|cannot|can't|couldn't|did not|didn't)\s+find\b"
        r"|\b(?:context|sources?|documents?|data)\s+(?:does not|do not|doesn't|don't)\s+"
        r"(?:contain|provide|include|mention)\b"
        r"|\b(?:ich|wir)\s+(?:kann|können|konnte|konnten|habe|haben)\b[^.!?\n]{0,100}"
        r"\bkeine?\b[^.!?\n]{0,100}\b(?:finden|gefunden)\b",
        text, re.IGNORECASE,
    ))


def prepare_response(text, sources):
    if not is_no_answer(text):
        # A clarification without cited evidence needs no retrieved-source panel.
        has_evidence = bool(re.search(r"\[\d+\]|https?://", text))
        return text, sources if has_evidence else []
    # Includes links generated by the model, not just backend-added links.
    text = re.sub(r"\[[^\]]*\]\(https?://[^\s)]+\)", "", text)
    text = re.sub(r"https?://[^\s<>]+", "", text)
    text = re.sub(r"\[\d+\]", "", text)
    text = re.sub(r"\n{3,}", "\n\n", text).strip()
    return text, []
